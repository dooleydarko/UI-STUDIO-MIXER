import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';

const port=4389;
const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port',String(port),'--strictPort'],{stdio:'inherit'});
let browser;
try {
  const url='http://127.0.0.1:'+port+'/tests/surface-browser.html';
  let ready=false;
  for(let i=0;i<80;i++){try{if((await fetch(url)).ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,250));}
  assert(ready,'Vite browser fixture never started');
  browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  const page=await browser.newPage();
  page.on('pageerror',e=>console.error('Browser error:',e.message));
  await page.goto(url);
  await page.waitForFunction(()=>!!window.surfaceTest,{timeout:30000});
  const results=await page.evaluate(async()=>{
    const {THREE,engine,psd,library}=window.surfaceTest;
    const check=(value,message)=>{if(!value)throw new Error(message);};
    const canvas=(w,h)=>{const c=document.createElement('canvas');c.width=w;c.height=h;return c;};
    const base=canvas(16,16),ctx=base.getContext('2d');
    ctx.fillStyle='#204060';ctx.fillRect(0,0,16,16);ctx.clearRect(0,0,2,2);
    const map=new THREE.CanvasTexture(base);map.colorSpace=THREE.SRGBColorSpace;map.flipY=false;
    const normal=new THREE.Texture();
    const material=new THREE.MeshStandardMaterial({map,normalMap:normal,roughness:.4,metalness:.3});
    const session=new engine.TextureCanvasSession(material,'Cover');
    const pix=(x,y)=>[...session.output.getContext('2d').getImageData(x,y,1,1).data];
    const gray={...engine.layerDefaults('Gray Out'),kind:'gray',color:'#808080'};
    const artwork=canvas(4,4),a=artwork.getContext('2d');a.fillStyle='#ff0000';a.fillRect(0,0,4,4);
    const art={...engine.layerDefaults('Artwork'),kind:'image',image:artwork.toDataURL(),x:5,y:5,width:4,height:4,rotation:0,flipX:false,flipY:false};
    const paint={...engine.layerDefaults('Paint'),kind:'paint',strokes:[{points:[{x:13,y:13}],color:'#00ff00',size:3,opacity:1,erase:false}]};
    const masked={...gray,mask:[{points:[{x:12,y:3}],color:'#ffffff',size:3,opacity:1,erase:true}],maskEnabled:true};
    const doc={...session.initial,layers:[masked,art,paint]};
    check(await session.render(doc),'Composite render did not complete');
    check(pix(0,0)[3]===0,'Original alpha cutout changed');
    check(pix(4,4)[0]===128,'Gray layer failed');
    check(pix(6,6)[0]===255&&pix(6,6)[1]===0,'Artwork placement failed');
    check(pix(13,13)[1]===255,'Paint layer failed');
    check(pix(12,3)[0]===32,'Mask did not reveal original');
    check(material.normalMap===normal&&material.roughness===.4&&material.metalness===.3,'Physical channels changed');
    const clone=engine.createClonePatch(session.output,[{x:10,y:10}],{x:6,y:6},2);
    check(clone.startsWith('data:image/png;base64,'),'Clone patch not exported');
    const bytes=await psd.exportTexturePsd(session,doc);
    const imported=await psd.importTexturePsd(new File([bytes],'roundtrip.psd'),session.initial);
    check(imported.document.layers.length===3,'PSD layer count changed');
    check(imported.document.layers.map(l=>l.name).join('|')==='Gray Out|Artwork|Paint','PSD order changed');
    check(!!imported.document.layers[0].maskImage,'PSD user mask was not preserved');
    await session.render(imported.document);
    check(pix(6,6)[0]===255&&pix(0,0)[3]===0,'PSD round-trip changed artwork or alpha');
    const original=new Blob(['source']),baked=new Blob(['baked']);
    const saved=await library.saveSurfaceProject('Browser fixture',baked,{source:original,sourceName:'fixture.glb',materialIndex:0,materialName:'Cover',document:doc,lighting:'studio',projectId:'fixture'});
    const restored=await library.readSurfaceProject(saved.id);
    check(restored.document.layers.length===3&&await restored.source.text()==='source','Layered project source or document not retained');
    await library.saveSurfaceDraft(saved.id,'fixture',imported.document,'neon');
    const draft=await library.readSurfaceProject(saved.id);
    check(draft.lighting==='neon'&&!!draft.document.layers[0].maskImage,'Draft autosave did not restore latest edits');
    check(await (await library.readSavedModel(saved.id)).text()==='baked','Draft autosave overwrote baked copy');
    await library.removeSavedModel(saved.id);
    session.showOriginal(true);check(material.map===map,'Original comparison failed');
    session.restore();check(material.map===map&&material.normalMap===normal,'Session restoration failed');
    return ['actual Canvas alpha / Gray Out / artwork / paint / mask','Clone Stamp patch','layered PSD adapter round-trip','IndexedDB editable project + autosave','original PBR restoration'];
  });
  assert.equal(results.length,5);
  console.log('Browser acceptance passed:',results);
}finally{await browser?.close();server.kill();}
